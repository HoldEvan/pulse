/** UUID 工具二级页：生成随机 UUID、校验输入、规范化紧凑格式 */
@Composable
fun UuidToolScreen(modifier: Modifier = Modifier) {
    var input by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf(UuidTool.generate()) }
    var compact by remember { mutableStateOf(false) }

    val normalized = remember(input) { UuidTool.normalize(input) }
    val isValid = remember(input) { input.isNotBlank() && UuidTool.isValid(input) }

    Column(
        modifier = modifier
            .fillMaxSize()
            .subPageOverScroll()
            .verticalScroll(subPageScrollState())
            .padding(start = 12.dp, top = LocalTopBarInset.current, end = 12.dp)
            .padding(bottom = 12.dp)
    ) {
        CardSectionTitle(text = stringResource(R.string.uuid_generate_label))
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            AppTextButton(
                text = stringResource(R.string.uuid_refresh),
                onClick = { generated = UuidTool.generate() },
                modifier = Modifier.weight(1f)
            )
            AppTextButton(
                text = stringResource(if (compact) R.string.uuid_show_dash else R.string.uuid_hide_dash),
                onClick = { compact = !compact },
                modifier = Modifier.weight(1f)
            )
        }
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(top = 8.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            MonospaceBlock(
                text = if (compact) generated.replace("-", "") else generated,
                modifier = Modifier.weight(1f)
            )
            Spacer(modifier = Modifier.padding(horizontal = 4.dp))
            CopyIconButton(
                text = if (compact) generated.replace("-", "") else generated,
                label = stringResource(R.string.action_copy)
            )
        }

        CardSectionTitle(text = stringResource(R.string.uuid_check_label), modifier = Modifier.padding(top = 16.dp))
        AppTextField(
            value = input,
            onValueChange = { input = it },
            label = stringResource(R.string.uuid_input_hint),
            modifier = Modifier.fillMaxWidth()
        )
        if (input.isNotBlank()) {
            AppText(
                text = stringResource(
                    if (isValid) R.string.uuid_valid else R.string.uuid_invalid
                ),
                modifier = Modifier.padding(vertical = 6.dp),
                fontSize = 13.sp,
                color = if (isValid) AppTheme.colors.primary else AppTheme.colors.error
            )
            if (isValid) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    CardSectionTitle(text = stringResource(R.string.uuid_normalized_label))
                    CopyIconButton(
                        text = normalized,
                        label = stringResource(R.string.action_copy)
                    )
                }
                MonospaceBlock(text = normalized.orEmpty(), modifier = Modifier.padding(top = 4.dp))
            }
        }
    }
}